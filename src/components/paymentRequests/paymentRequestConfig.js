// Nhận cả 'yyyy-MM-dd' lẫn ISO datetime; tránh lệch ngày do múi giờ khi chỉ có ngày.
export const fmtDate = (value) => {
    if (!value) return '-';
    const m = String(value).match(/^(\d{4})-(\d{2})-(\d{2})/);
    if (m) return `${m[3]}/${m[2]}/${m[1]}`;
    return formatDate(value) || '-';
};

